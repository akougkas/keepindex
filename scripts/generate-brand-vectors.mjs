function number(value) {
  const rounded = Math.round(value * 1_000_000) / 1_000_000
  return Object.is(rounded, -0) ? '0' : String(rounded)
}

function layoutText({ text, font, size, letterSpacing = 0 }) {
  const run = font.layout(text)
  const scale = size / font.unitsPerEm
  const glyphs = []
  let cursor = 0

  run.glyphs.forEach((glyph, index) => {
    const position = run.positions[index]
    const path = glyph.path.toSVG()
    if (path) {
      glyphs.push(
        `<path d="${path}" transform="translate(${number(cursor + position.xOffset)} ${number(position.yOffset)})"/>`,
      )
    }
    cursor += position.xAdvance
    if (index < run.glyphs.length - 1) cursor += letterSpacing / scale
  })

  return {
    glyphs: glyphs.join(''),
    scale,
    width: cursor * scale,
  }
}

function outlinedText({
  text,
  font,
  size,
  x,
  y,
  fill,
  letterSpacing = 0,
  anchor = 'start',
}) {
  const layout = layoutText({ text, font, size, letterSpacing })
  const start = anchor === 'end' ? x - layout.width : anchor === 'middle' ? x - layout.width / 2 : x
  return {
    svg: `<g fill="${fill}" transform="translate(${number(start)} ${number(y)}) scale(${number(layout.scale)} ${number(-layout.scale)})">${layout.glyphs}</g>`,
    width: layout.width,
  }
}

function outlinedSegments({ segments, font, size, x, y, letterSpacing = 0, anchor = 'start' }) {
  const layouts = segments.map((segment) => ({
    ...segment,
    layout: layoutText({ text: segment.text, font, size, letterSpacing }),
  }))
  const gapWidth = letterSpacing * Math.max(0, layouts.length - 1)
  const totalWidth = layouts.reduce((sum, segment) => sum + segment.layout.width, 0) + gapWidth
  let cursor = anchor === 'end' ? x - totalWidth : anchor === 'middle' ? x - totalWidth / 2 : x
  const svg = layouts.map((segment, index) => {
    const group = `<g fill="${segment.fill}" transform="translate(${number(cursor)} ${number(y)}) scale(${number(segment.layout.scale)} ${number(-segment.layout.scale)})">${segment.layout.glyphs}</g>`
    cursor += segment.layout.width + (index < layouts.length - 1 ? letterSpacing : 0)
    return group
  }).join('')
  return { svg, width: totalWidth }
}

