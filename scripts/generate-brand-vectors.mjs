function prepareVariableFont(path) {
  const font = openSync(path)
  if (!font || typeof font.layout !== 'function' || !font.variationAxes?.wght) {
    throw new Error(`Expected a variable Latin font at ${path}`)
  }

  // Force fontkit to decode the WOFF2 directory and transformed glyph table
  // once. Variations then share those deterministic, in-memory source tables.
  void font.unitsPerEm
  const probe = font.layout('KeepIndex · Search your world. Keep it yours.')
  const probeGlyph = probe.glyphs.find((glyph) => glyph.path.toSVG().length > 0)
  if (!probeGlyph) throw new Error(`Could not decode glyph outlines from ${path}`)
  return font
}

function fontVariation(source, weight) {
  const variation = source.getVariation({ wght: weight })

  // fontkit 2.0.4 reconstructs a plain TTF wrapper for a WOFF2 variation.
  // Reattach the already decoded WOFF2 tables so the public path API uses the
  // requested variation coordinates without relying on an installed font.
  Object.setPrototypeOf(variation, Object.getPrototypeOf(source))
  variation.directory = source.directory
  variation.stream = source.stream
  variation._decompressed = true
  variation._dataPos = source._dataPos
  variation._transformedGlyphs = source._transformedGlyphs
  for (const [tag, table] of Object.entries(source.directory.tables)) {
    if (!Object.hasOwn(variation, tag)) {
      Object.defineProperty(variation, tag, {
        get: variation._getTable.bind(variation, table),
      })
    }
  }
  return variation
}

